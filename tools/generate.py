#!/usr/bin/env python3
"""
Regenerates install.sh and docs/PopOS-Customization-Guide.docx from entries.json.

entries.json is the single source of truth. Run this after editing entries.json
(normally that editing is done by Claude Code on request, one tool/customization
at a time) so the script and the Word doc never drift apart.

Usage: python3 tools/generate.py
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from docx_writer import DocxBuilder  # noqa: E402

ENTRIES_PATH = ROOT / "entries.json"
SCRIPT_PATH = ROOT / "install.sh"
DOC_PATH = ROOT / "docs" / "PopOS-Customization-Guide.docx"


def load():
    with open(ENTRIES_PATH) as f:
        return json.load(f)


def default_map(data):
    """Collect non-secret {{TOKEN}} -> default from every entry's params.

    Secret params (e.g. NAS_PASSWORD) are intentionally excluded: they are
    referenced in commands as ${TOKEN:-} shell variables, never as {{TOKEN}}
    text, so they are never baked into install.sh or the Word guide.
    """
    defaults = {}
    for e in data["entries"]:
        for p in e.get("params") or []:
            if p.get("secret"):
                continue
            defaults[p["token"]] = p.get("default", "")
    return defaults


def resolve(cmds, defaults):
    """Substitute {{TOKEN}} with its default value in each command line."""
    out = []
    for c in cmds:
        for tok, val in defaults.items():
            c = c.replace("{{" + tok + "}}", val)
        out.append(c)
    return out


def build_script(data):
    defaults = default_map(data)
    lines = []
    lines.append("#!/usr/bin/env bash")
    lines.append("# Auto-generated by tools/generate.py from entries.json -- DO NOT EDIT BY HAND.")
    lines.append("# To change anything: edit entries.json, then run: python3 tools/generate.py")
    lines.append("#")
    lines.append(f"# Distro: {data['distro_name']}")
    base = data["base"]
    lines.append(f"# Base:   {base['name']} {base['version']} ({base['codename']})")
    lines.append(f"# Regenerated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    lines.append("")
    lines.append("set -euo pipefail")
    lines.append("")
    lines.append('echo "=== ' + data["distro_name"] + ' -- install script ==="')
    lines.append("")

    for e in data["entries"]:
        lines.append("# " + "-" * 75)
        lines.append(f"# [{e['id']}] {e['category']}: {e['name']}  ({e['date']})")
        lines.append("# " + "-" * 75)
        for dline in wrap_comment(e.get("description", "")):
            lines.append(f"# {dline}")
        cmds = resolve(e.get("commands") or [], defaults)
        if cmds:
            lines.append(f'echo ">>> [{e["id"]}] {e["name"]}"')
            lines.extend(cmds)
        else:
            lines.append("# (documentation-only entry -- no shell commands)")
        lines.append("")

    lines.append('echo "=== Done. ==="')
    lines.append("")
    return "\n".join(lines)


def wrap_comment(text, width=90):
    import textwrap
    if not text:
        return []
    return textwrap.wrap(text, width=width)


def build_doc(data):
    defaults = default_map(data)
    doc = DocxBuilder(doc_title=data["distro_name"])
    doc.title(data["distro_name"])
    doc.subtitle("Pop!_OS Customization & Custom Distro Build Log")
    doc.paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    doc.paragraph(f"Owner: {data.get('owner_email', '')}")
    doc.spacer()

    doc.heading("Overview", 1)
    doc.paragraph(
        "This document is the step-by-step record of every tool installed and every "
        "customization applied to this Pop!_OS machine. It is generated automatically "
        "from entries.json, the single source of truth for this project -- the same "
        "file also generates install.sh, so the written procedure and the runnable "
        "script can never drift apart. Each time a new tool or tweak is requested, a "
        "new entry is appended to entries.json and both outputs are regenerated."
    )
    doc.paragraph(
        "Goal: once the tool list is complete, use this record (and install.sh) as the "
        "customization layer for building a personal Pop!_OS-based distro image. See "
        "the final section of this document for that process."
    )

    doc.heading("System Baseline", 1)
    base = data["base"]
    doc.bullet(f"Base distribution: {base['name']} {base['version']} ({base['codename']})")
    doc.bullet(f"Project started: {data['started']}")
    doc.bullet("Architecture: amd64")

    doc.heading("Installed Software & Customizations", 1)
    doc.paragraph(
        "Entries are listed in the order they were requested. Each entry shows what "
        "was installed/changed, why, and the exact command(s) used."
    )
    for e in data["entries"]:
        doc.heading(f"{e['id']}. {e['name']}", 2)
        doc.paragraph(f"Category: {e['category']}   |   Date: {e['date']}   |   Method: {e.get('method', 'manual')}", italic=True)
        if e.get("description"):
            doc.paragraph(e["description"])
        cmds = resolve(e.get("commands") or [], defaults)
        if cmds:
            doc.heading("Commands", 3)
            doc.code(cmds)
        if e.get("notes"):
            doc.paragraph("Note: " + e["notes"], italic=True)
        doc.spacer()

    doc.page_break()
    doc.heading("Next Steps: Building Your Own Pop!_OS-Based Distro", 1)
    doc.paragraph(
        "Once this list reflects everything you want on a fresh install, install.sh "
        "becomes the 'customization layer' you bake into a respin. Three common paths:"
    )
    doc.heading("Option A -- Cubic (easiest)", 2)
    doc.paragraph(
        "Cubic (Custom Ubuntu ISO Creator) lets you boot the stock Pop!_OS ISO into a "
        "chroot-like terminal, run install.sh (and any GUI installs) inside it, then "
        "repack it as a new bootable ISO. Best for a personal remix; least effort."
    )
    doc.bullet("Install Cubic from its PPA or Flatpak")
    doc.bullet("Point it at the official Pop!_OS 24.04 ISO")
    doc.bullet("In the chroot terminal it opens, run install.sh")
    doc.bullet("Finish the wizard to produce a new custom .iso")

    doc.heading("Option B -- live-build / debootstrap (full control)", 2)
    doc.paragraph(
        "Use debootstrap or Debian/Ubuntu's live-build tooling to construct a fresh "
        "filesystem from Pop!_OS/Ubuntu noble repos, install.sh runs as a chroot "
        "hook, then squashfs + an ISO/EFI boot layer are built around it. More work, "
        "but fully scriptable and reproducible in CI."
    )

    doc.heading("Option C -- OEM/first-boot script (no custom ISO at all)", 2)
    doc.paragraph(
        "Skip ISO respinning entirely: install stock Pop!_OS, then run install.sh as "
        "a one-time provisioning script on any new machine. Lowest effort, no image "
        "maintenance, but each machine needs an internet connection and the run."
    )

    doc.heading("Recommendation", 2)
    doc.paragraph(
        "Start with Option C (just running install.sh on a fresh install) to validate "
        "the script end-to-end. Move to Option A (Cubic) only once you want a "
        "hand-a-USB-stick-to-someone artifact."
    )

    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(DOC_PATH))


def main():
    data = load()
    SCRIPT_PATH.write_text(build_script(data))
    SCRIPT_PATH.chmod(0o755)
    build_doc(data)
    print(f"Wrote {SCRIPT_PATH}")
    print(f"Wrote {DOC_PATH}")


if __name__ == "__main__":
    main()
